#!/usr/bin/env node
// Copies the backend's historical v0.2 bundle report.json, byte for byte, into a TS module so the
// fixture API can serve /raw and the browser can recompute its SHA-256. Content is not edited.
//   BACKEND_REPO_PATH=../ScoobyDAO-backend node scripts/gen-fixtures.mjs
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const backend = path.resolve(root, process.env.BACKEND_REPO_PATH ?? '../ScoobyDAO-backend');
const bundle = path.join(backend, 'tests/historical-bundle');
const raw = fs.readFileSync(path.join(bundle, 'report.json'));
const digest = JSON.parse(fs.readFileSync(path.join(bundle, 'digest.json'), 'utf8'));
const sha = crypto.createHash('sha256').update(raw).digest('hex');
if (sha !== digest.sha256) throw new Error(`report.json sha256 ${sha} != digest.json ${digest.sha256}`);
const text = raw.toString('utf8');
if (Buffer.from(text, 'utf8').compare(raw) !== 0) throw new Error('report.json is not round-trip UTF-8');
const out = `// GENERATED by scripts/gen-fixtures.mjs from ScoobyDAO-backend/tests/historical-bundle. Do not edit.
// Exact report.json bytes (UTF-8). digest.json sha256: ${digest.sha256}
export const HISTORICAL_REPORT_JSON = ${JSON.stringify(text)};
export const HISTORICAL_DIGEST_SHA256 = ${JSON.stringify(digest.sha256)};
`;
fs.writeFileSync(path.join(root, 'src/fixtures/historicalReport.ts'), out);
console.log(`Wrote src/fixtures/historicalReport.ts (${raw.length} bytes, sha256 ${sha})`);
