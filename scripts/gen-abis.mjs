#!/usr/bin/env node
// Generates src/contracts/generated.ts from Foundry build output.
// Reads <out>/<File>.sol/<Contract>.json (the `abi` field only). Nothing here is hand-written.
//
//   CONTRACTS_OUT=../SmartContracts/out node scripts/gen-abis.mjs
//
// Default out dir: $CONTRACTS_REPO_PATH/out, else ../SmartContracts/out.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repo = path.resolve(root, process.env.CONTRACTS_REPO_PATH ?? '../SmartContracts');
const outDir = path.resolve(root, process.env.CONTRACTS_OUT ?? path.join(repo, 'out'));

// [export name, contract name, optional filter of ABI item names]
const ERC20_SUBSET = [
  'name', 'symbol', 'decimals', 'totalSupply', 'balanceOf', 'allowance', 'approve', 'transfer',
  'transferFrom', 'Transfer', 'Approval',
];
const CONTRACTS = [
  ['reportRegistryAbi', 'ReportRegistry'],
  ['voteMarketAbi', 'VoteMarket'],
  ['votingPositionTokenAbi', 'VotingPositionToken'],
  ['settlementAbi', 'Settlement'],
  ['reputationAbi', 'Reputation'],
  ['treasuryAbi', 'Treasury'],
  ['demoUsdAbi', 'DemoUSD', ERC20_SUBSET],
  ['yieldSplitterAbi', 'YieldSplitter'],
  ['yieldVaultAdapterAbi', 'YieldVaultAdapter'],
  ['yieldTokenAbi', 'YieldToken'],
  ['yieldHookFactoryAbi', 'YieldHookFactory'],
  ['yieldMarketHookAbi', 'YieldMarketHook'],
  ['yieldSwapRouterAbi', 'YieldSwapRouter'],
  ['yieldLpShareAbi', 'YieldLPShare'],
  ['ccipStakeSenderAbi', 'CCIPStakeSender'],
  ['ccipStakeReceiverAbi', 'CCIPStakeReceiver'],
  // V2 ABIs are not generated here: they come from the contracts handoff bundle (npm run sync:v2).
];

if (!fs.existsSync(outDir)) {
  console.error(`No Foundry out/ at ${outDir}. Run \`forge build\` in the contracts repo first.`);
  process.exit(1);
}

function artifact(name) {
  const direct = path.join(outDir, `${name}.sol`, `${name}.json`);
  if (fs.existsSync(direct)) return JSON.parse(fs.readFileSync(direct, 'utf8'));
  for (const d of fs.readdirSync(outDir)) {
    const f = path.join(outDir, d, `${name}.json`);
    if (fs.existsSync(f)) return JSON.parse(fs.readFileSync(f, 'utf8'));
  }
  throw new Error(`Artifact for ${name} not found in ${outDir}`);
}

let ts = `// GENERATED by scripts/gen-abis.mjs from Foundry build output. Do not edit by hand.\n`;
ts += `// Source: ${path.relative(root, outDir) || outDir}\n\n`;
for (const [exportName, contract, filter] of CONTRACTS) {
  let abi = artifact(contract).abi;
  if (filter) abi = abi.filter((i) => i.name && filter.includes(i.name));
  ts += `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
const dest = path.join(root, 'src/contracts/generated.ts');
fs.writeFileSync(dest, ts);
console.log(`Wrote ${CONTRACTS.length} ABIs to ${path.relative(root, dest)}`);
