#!/usr/bin/env node
// Generates src/lib/report.generated.ts from the backend's frozen report v0.2 JSON Schema.
//   BACKEND_REPO_PATH=../ScoobyDAO-backend node scripts/gen-report-types.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const backend = path.resolve(root, process.env.BACKEND_REPO_PATH ?? '../ScoobyDAO-backend');
const schemaPath = path.join(backend, 'schemas/report.schema.json');
const schema = JSON.parse(fs.readFileSync(schemaPath, 'utf8'));
const ts = await compile(schema, 'ReportV02', {
  bannerComment:
    '// GENERATED by scripts/gen-report-types.mjs from ScoobyDAO-backend/schemas/report.schema.json (v0.2, frozen).\n// Do not edit by hand.',
  additionalProperties: false,
  strictIndexSignatures: true,
  style: { singleQuote: true },
  cwd: path.dirname(schemaPath),
});
fs.writeFileSync(path.join(root, 'src/lib/report.generated.ts'), ts);
console.log('Wrote src/lib/report.generated.ts');
