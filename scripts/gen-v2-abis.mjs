#!/usr/bin/env node
// Generates src/contracts/v2/abis.ts from the V2 handoff bundle copied into src/contracts/v2.
// The bundle's abis/*.json are raw ABI arrays; this module re-exports them `as const` so viem and
// wagmi keep literal types. Every file must match abi-manifest.json (SHA-256 and entry count),
// and the manifest must list exactly the files present, or nothing is written.
//
//   node scripts/gen-v2-abis.mjs              verify src/contracts/v2 and write abis.ts
//   node scripts/gen-v2-abis.mjs --check DIR  verify a bundle directory only (used by sync-v2.sh)
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const v2Dir = path.join(root, 'src/contracts/v2');

// Manifest contract name → export name. A new contract in the bundle must be added here on purpose.
const EXPORTS = {
  BurnMintTokenPool: 'burnMintTokenPoolAbi',
  CCIPStakeReceiverV2: 'ccipStakeReceiverV2Abi',
  CCIPStakeSenderV2: 'ccipStakeSenderV2Abi',
  DemoUSD: 'demoUsdAbi',
  ReportRegistry: 'reportRegistryAbi',
  RiskFiStakeVaultV2: 'riskFiStakeVaultV2Abi',
  StakeAndSellRouterV2: 'stakeAndSellRouterV2Abi',
  StakeReceiptREP: 'stakeReceiptRepAbi',
  StakerYieldToken: 'stakerYieldTokenAbi',
  YieldCurveFactoryV2: 'yieldCurveFactoryV2Abi',
  YieldCurveHookV2: 'yieldCurveHookV2Abi',
  YieldLPShare: 'yieldLpShareAbi',
  YieldSwapRouter: 'yieldSwapRouterAbi',
};

/** Returns [[contract, abi]] or throws with every problem found. */
export function verifyBundle(dir) {
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'abi-manifest.json'), 'utf8'));
  const problems = [];
  const out = [];
  for (const [contract, entry] of Object.entries(manifest)) {
    if (!EXPORTS[contract]) problems.push(`${contract}: not in scripts/gen-v2-abis.mjs EXPORTS`);
    const file = path.join(dir, entry.file);
    if (!fs.existsSync(file)) {
      problems.push(`${contract}: ${entry.file} is missing`);
      continue;
    }
    const bytes = fs.readFileSync(file);
    const sha = crypto.createHash('sha256').update(bytes).digest('hex');
    if (sha !== entry.sha256) problems.push(`${contract}: sha256 ${sha} != manifest ${entry.sha256}`);
    const abi = JSON.parse(bytes.toString('utf8'));
    if (!Array.isArray(abi)) problems.push(`${contract}: ${entry.file} is not a raw ABI array`);
    else if (abi.length !== entry.entries) problems.push(`${contract}: ${abi.length} entries != manifest ${entry.entries}`);
    out.push([contract, abi]);
  }
  const listed = new Set(Object.values(manifest).map((e) => path.normalize(e.file)));
  for (const f of fs.readdirSync(path.join(dir, 'abis'))) {
    if (f.endsWith('.json') && !listed.has(path.join('abis', f))) problems.push(`abis/${f} is not listed in abi-manifest.json`);
  }
  if (problems.length) throw new Error(`V2 bundle at ${dir} failed verification:\n  ${problems.join('\n  ')}`);
  return out;
}

const args = process.argv.slice(2);
try {
  if (args[0] === '--check') {
    verifyBundle(path.resolve(args[1] ?? v2Dir));
    console.log(`V2 bundle at ${args[1]} matches its abi-manifest.json`);
  } else {
    writeAbis();
  }
} catch (e) {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
}

function writeAbis() {
  const abis = verifyBundle(v2Dir);
  const version = JSON.parse(fs.readFileSync(path.join(v2Dir, 'addresses.json'), 'utf8')).version;
  let ts = `// GENERATED by scripts/gen-v2-abis.mjs from src/contracts/v2/abis/*.json (bundle ${version}). Do not edit by hand.\n`;
  ts += `// Run \`npm run sync:v2\` to copy a new handoff bundle, verify it against abi-manifest.json and regenerate.\n\n`;
  for (const [contract, abi] of abis) ts += `export const ${EXPORTS[contract]} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
  ts += `export const v2Abis = {\n${abis.map(([c]) => `  ${c}: ${EXPORTS[c]},`).join('\n')}\n} as const;\n`;
  fs.writeFileSync(path.join(v2Dir, 'abis.ts'), ts);
  console.log(`Wrote ${abis.length} V2 ABIs to src/contracts/v2/abis.ts`);
}
